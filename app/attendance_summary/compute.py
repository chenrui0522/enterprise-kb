_DEPART_MARK_RE = _re.compile(
    r"[（(\[【][^）)\]】]*(?:已)?离职[^）)\]】]*[）)\]】]"
)
_SPACE_AROUND_DOT_RE = _re.compile(r"\s*\.\s*")
_MULTI_SPACE_RE = _re.compile(r"\s+")


def normalize_person_name(name: str) -> str:  # type: ignore[no-redef]
    text = str(name or "").strip()
    stripped = _DEPART_MARK_RE.sub("", text).strip()
    base = _orig_normalize_person_name(stripped or text) or (stripped or text)
    # Collapse "W. Umaporn" / "W.Umaporn" and internal whitespace for punch↔roster join.
    compact = _SPACE_AROUND_DOT_RE.sub(".", base)
    compact = _MULTI_SPACE_RE.sub("", compact)
    # Unify common interpuncts used in Uyghur / compound names (· vs •).
    compact = compact.replace("·", "•").replace("･", "•").replace("・", "•")
    return compact or base


def person_name_marked_departed(name: str) -> bool:  # type: ignore[no-redef]
    if _orig_person_name_marked_departed(name):
        return True
    text = str(name or "")
    return bool(_DEPART_MARK_RE.search(text)) or ("离职" in text and "在职" not in text)


def apply_default_base_site(
    roster: list,
    *,
    default_base_site: str | None = DEFAULT_BASE_SITE,
) -> list:
    """Fill empty roster base_site with temporary default (太原 until roster ships)."""
    if not default_base_site:
        return list(roster)
    out = []
    for person in roster:
        site = str(getattr(person, "base_site", "") or "").strip()
        out.append(person if site else _dc_replace(person, base_site=default_base_site))
    return out


def _person_base_site(roster: list, name: str, default_base_site: str) -> str:
    key = normalize_person_name(name)
    for person in roster:
        if normalize_person_name(getattr(person, "name", "")) == key:
            site = str(getattr(person, "base_site", "") or "").strip()
            return site or default_base_site
    return default_base_site


def _first_field_day(
    punches: list,
    *,
    person: str,
    base_site: str,
    start: _date,
    end: _date,
) -> _date | None:
    """First day in range with field/other_company punch (not home_transit)."""
    key = normalize_person_name(person)
    best: _date | None = None
    for punch in punches:
        if normalize_person_name(getattr(punch, "person_name", "")) != key:
            continue
        wd = getattr(punch, "work_date", None)
        if not isinstance(wd, _date) or wd < start or wd > end:
            continue
        loc = _classify_side(
            address=str(getattr(punch, "address", "") or ""),
            status=str(getattr(punch, "status", "") or ""),
            base_site=base_site,
        )
        if getattr(loc, "kind", "") in {"field", "other_company"}:
            if best is None or wd < best:
                best = wd
    return best


def shift_travel_start_past_predeparture_base(
    travel: list,
    punch: list,
    roster: list,
    *,
    default_base_site: str = DEFAULT_BASE_SITE,
    overseas_keywords: list | None = None,
) -> list:
    """Avoid permanent trip-kill when start days are still at base before departure.

    Bytecode early-return clip ends the whole trip after pre-departure base punches;
    shift effective start to the first field/other_company day inside the approval window.

    Only applied for overseas-location approvals (国内行程 keep approval start so
    late-depart / transit days still count).
    """
    ovs = [str(k).strip() for k in (overseas_keywords or []) if str(k).strip()]
    out = []
    for row in travel:
        status = str(getattr(row, "status", "") or "")
        start = getattr(row, "start", None)
        end = getattr(row, "end", None)
        location = str(getattr(row, "location", "") or "")
        if "通过" not in status or not isinstance(start, _date) or not isinstance(end, _date):
            out.append(row)
            continue
        is_overseas = any(k in location for k in ovs) or bool(
            _address_hits_overseas(location, ovs)
        )
        if not is_overseas:
            out.append(row)
            continue
        applicant = str(getattr(row, "applicant", "") or "")
        base = _person_base_site(roster, applicant, default_base_site)
        field_day = _first_field_day(
            punch, person=applicant, base_site=base, start=start, end=end
        )
        if field_day is None or field_day <= start:
            out.append(row)
            continue
        start_at = getattr(row, "start_at", None)
        new_start_at = _datetime.combine(field_day, _time(0, 0))
        if isinstance(start_at, _datetime):
            new_start_at = _datetime.combine(field_day, start_at.time())
        out.append(
            _dc_replace(row, start=field_day, start_at=new_start_at)
            if hasattr(row, "__dataclass_fields__")
            else row
        )
    return out


def _address_hits_overseas(address: str, overseas_keywords: list) -> str | None:
    text = str(address or "")
    if not text:
        return None
    for kw in overseas_keywords or []:
        token = str(kw or "").strip()
        if token and token in text:
            return token
    # Latin fallbacks often present when Chinese keyword missing in address
    lower = text.lower()
    for token in ("thailand", "vietnam", "indonesia", "singapore", "malaysia"):
        if token in lower:
            return token
    return None


def synthesize_overseas_travel_from_punches(
    travel: list,
    punch: list,
    roster: list,
    *,
    overseas_keywords: list,
    year: int,
    month: int,
    default_base_site: str = DEFAULT_BASE_SITE,
) -> list:
    """When punches show overseas address but no covering approval, add synthetic travel.

    Covers operators like 宫瑞宏 (Thailand punches, no 出差审批) so 国外出差 can accrue.
    """
    covered: set[tuple[str, _date]] = set()
    for row in travel:
        if "通过" not in str(getattr(row, "status", "") or ""):
            continue
        start = getattr(row, "start", None)
        end = getattr(row, "end", None)
        if not isinstance(start, _date) or not isinstance(end, _date):
            continue
        key = normalize_person_name(getattr(row, "applicant", ""))
        cur = start
        while cur <= end:
            covered.add((key, cur))
            cur = _date.fromordinal(cur.toordinal() + 1)

    by_person: dict[str, list[_date]] = {}
    loc_label: dict[str, str] = {}
    for p in punch:
        wd = getattr(p, "work_date", None)
        if not isinstance(wd, _date) or wd.year != year or wd.month != month:
            continue
        hit = _address_hits_overseas(
            str(getattr(p, "address", "") or ""), overseas_keywords
        )
        if not hit:
            continue
        key = normalize_person_name(getattr(p, "person_name", ""))
        if not key or (key, wd) in covered:
            continue
        # Only field-side overseas; ignore if still classified as base_company
        base = _person_base_site(roster, key, default_base_site)
        loc = _classify_side(
            address=str(getattr(p, "address", "") or ""),
            status=str(getattr(p, "status", "") or ""),
            base_site=base,
        )
        if getattr(loc, "kind", "") == "base_company":
            continue
        by_person.setdefault(key, []).append(wd)
        loc_label.setdefault(key, hit)

    extras = list(travel)
    for key, days in by_person.items():
        uniq = sorted(set(days))
        if not uniq:
            continue
        # Merge contiguous runs into TravelRow(s)
        run_start = uniq[0]
        prev = uniq[0]
        runs: list[tuple[_date, _date]] = []
        for d in uniq[1:]:
            if d.toordinal() == prev.toordinal() + 1:
                prev = d
                continue
            runs.append((run_start, prev))
            run_start = prev = d
        runs.append((run_start, prev))
        # Prefer roster display name
        display = key
        for person in roster:
            if normalize_person_name(getattr(person, "name", "")) == key:
                display = str(getattr(person, "name", key))
                break
        label = loc_label.get(key) or "境外"
        for a, b in runs:
            extras.append(
                TravelRow(  # type: ignore[name-defined]
                    applicant=display,
                    department="",
                    center="",
                    category="打卡地址海外（合成）",
                    location=str(label),
                    start=a,
                    end=b,
                    status="已通过",
                    start_at=_datetime.combine(a, _time(0, 0)),
                    end_at=_datetime.combine(b, _time(23, 59)),
                )
            )
    return extras


def synthesize_domestic_field_travel_from_punches(
    travel: list,
    punch: list,
    roster: list,
    *,
    year: int,
    month: int,
    default_base_site: str = DEFAULT_BASE_SITE,
    overseas_keywords: list | None = None,
) -> list:
    """After an approved trip ends, keep counting domestic travel while punches stay field.

    Covers 张霄鹏: 审批止于 8/30，8/31 仍外勤（不在公司地点）→ ￥。Place-text overlap with
    the trip location is NOT required. Does NOT treat other_company / base_company as
    auto-travel. Overseas addresses stay with synthesize_overseas_travel_from_punches.
    """
    ovs = [str(k).strip() for k in (overseas_keywords or []) if str(k).strip()]
    covered: set[tuple[str, _date]] = set()
    # Real approvals only (exclude prior synthetics): person -> list of (start, end)
    real_trips: dict[str, list[tuple[_date, _date]]] = {}
    for row in travel:
        if "通过" not in str(getattr(row, "status", "") or ""):
            continue
        cat = str(getattr(row, "category", "") or "")
        start = getattr(row, "start", None)
        end = getattr(row, "end", None)
        if not isinstance(start, _date) or not isinstance(end, _date):
            continue
        key = normalize_person_name(getattr(row, "applicant", ""))
        cur = start
        while cur <= end:
            covered.add((key, cur))
            cur = _date.fromordinal(cur.toordinal() + 1)
        if "合成" in cat:
            continue
        real_trips.setdefault(key, []).append((start, end))

    # Per person/day: whether any punch is field / base_company (for continuity cut)
    day_field: dict[tuple[str, _date], str] = {}
    day_base: set[tuple[str, _date]] = set()
    for p in punch:
        wd = getattr(p, "work_date", None)
        if not isinstance(wd, _date) or wd.year != year or wd.month != month:
            continue
        status = str(getattr(p, "status", "") or "")
        if "缺卡" in status:
            continue
        addr = str(getattr(p, "address", "") or "")
        if not addr.strip() or _address_hits_overseas(addr, ovs):
            continue
        key = normalize_person_name(getattr(p, "person_name", ""))
        if not key:
            continue
        base = _person_base_site(roster, key, default_base_site)
        loc = _classify_side(address=addr, status=status, base_site=base)
        kind = getattr(loc, "kind", "")
        if kind == "base_company":
            day_base.add((key, wd))
        elif kind == "field":
            label = addr.split("|")[0].strip() or addr[:40]
            day_field.setdefault((key, wd), label)

    extras = list(travel)
    month_last = _date(year, month, 1)
    # last day of month
    if month == 12:
        month_last = _date(year, 12, 31)
    else:
        month_last = _date(year, month + 1, 1).fromordinal(
            _date(year, month + 1, 1).toordinal() - 1
        )

    for key, trips in real_trips.items():
        display = key
        for person in roster:
            if normalize_person_name(getattr(person, "name", "")) == key:
                display = str(getattr(person, "name", key))
                break
        for _start, ended in trips:
            # Must continue on the very next calendar day with field punch (no gap).
            # No place-overlap with trip location required — only「不在公司地点」.
            cur = _date.fromordinal(ended.toordinal() + 1)
            if cur > month_last or (key, cur) not in day_field:
                continue
            if (key, cur) in covered or (key, cur) in day_base:
                continue
            run_start = cur
            run_end = cur
            label = day_field[(key, cur)]
            cur = _date.fromordinal(cur.toordinal() + 1)
            while cur <= month_last:
                if (key, cur) in covered or (key, cur) in day_base:
                    break
                if (key, cur) not in day_field:
                    break
                label = day_field[(key, cur)]
                run_end = cur
                cur = _date.fromordinal(cur.toordinal() + 1)
            extras.append(
                TravelRow(  # type: ignore[name-defined]
                    applicant=display,
                    department="",
                    center="",
                    category="打卡外勤续差（合成）",
                    location=str(label),
                    start=run_start,
                    end=run_end,
                    status="已通过",
                    start_at=_datetime.combine(run_start, _time(0, 0)),
                    end_at=_datetime.combine(run_end, _time(23, 59)),
                )
            )
    return extras


def _sanitize_false_base_on_mixed_field_days(
    punch: list,
    roster: list,
    *,
    overseas_keywords: list,
    default_base_site: str = DEFAULT_BASE_SITE,
) -> list:
    """Clear bare company-label addresses on days that also have field/other_company.

    WeCom often labels one side as only「奥特莱物流科技有限公司」while the other
    side is Thailand / 朔州园区. That false base_company hit permanently clips travel.
    """
    field_days: set[tuple[str, _date]] = set()
    for p in punch:
        wd = getattr(p, "work_date", None)
        if not isinstance(wd, _date):
            continue
        key = normalize_person_name(getattr(p, "person_name", ""))
        addr = str(getattr(p, "address", "") or "")
        if _address_hits_overseas(addr, overseas_keywords):
            field_days.add((key, wd))
            continue
        base = _person_base_site(roster, key, default_base_site)
        loc = _classify_side(
            address=addr, status=str(getattr(p, "status", "") or ""), base_site=base
        )
        if getattr(loc, "kind", "") in {"field", "other_company"}:
            field_days.add((key, wd))
    out = []
    bare_company = _re.compile(
        r"^奥特莱物流科技有限公司(\s*\|\s*ATL-太原公司)?$"
    )
    for p in punch:
        wd = getattr(p, "work_date", None)
        key = normalize_person_name(getattr(p, "person_name", ""))
        addr = str(getattr(p, "address", "") or "").strip()
        if (
            isinstance(wd, _date)
            and (key, wd) in field_days
            and bare_company.match(addr)
            and not _address_hits_overseas(addr, overseas_keywords)
        ):
            out.append(_dc_replace(p, address=""))
        else:
            out.append(p)
    return out


def _day_covered_by_approved_travel(
    travel: list, *, person_key: str, day: _date
) -> str | None:
    for row in travel:
        if "通过" not in str(getattr(row, "status", "") or ""):
            continue
        if normalize_person_name(getattr(row, "applicant", "")) != person_key:
            continue
        start = getattr(row, "start", None)
        end = getattr(row, "end", None)
        if not isinstance(start, _date):
            continue
        if not isinstance(end, _date):
            end = start
        if start <= day <= end:
            return str(getattr(row, "location", "") or "")
    return None


def align_travel_symbol_on_punched_side_keep_missing(
    result,
    *,
    travel: list,
    punch: list,
    roster: list,
    overseas_keywords: list,
    default_base_site: str = DEFAULT_BASE_SITE,
):
    """On a travel day: punched side → ￥/＄; 缺卡 side stays × (须补卡抵消).

    Must NOT invent ￥ on the missing side (正确表手工双￥另豁免).
    """
    people = getattr(result, "people", None) or []
    punches_by_person: dict[str, list] = {}
    for p in punch:
        punches_by_person.setdefault(
            normalize_person_name(getattr(p, "person_name", "")), []
        ).append(p)

    year = getattr(result, "year", None)
    month = getattr(result, "month", None)
    if not isinstance(year, int) or not isinstance(month, int):
        return result

    for person in people:
        key = normalize_person_name(getattr(person, "name", ""))
        base = _person_base_site(roster, key, default_base_site)
        syms = getattr(person, "day_symbols", None)
        if not isinstance(syms, dict):
            continue
        for day_key, cell in list(syms.items()):
            if isinstance(day_key, int):
                day_num = day_key
            elif isinstance(day_key, str) and day_key.isdigit():
                day_num = int(day_key)
            else:
                continue
            try:
                day = _date(year, month, day_num)
            except ValueError:
                continue
            if not isinstance(cell, dict):
                continue

            loc = _day_covered_by_approved_travel(travel, person_key=key, day=day)
            day_punches = [
                p
                for p in punches_by_person.get(key, [])
                if getattr(p, "work_date", None) == day
            ]
            leave_bits = " ".join(
                str(getattr(p, "leave_apply", "") or "") for p in day_punches
            )
            has_leave_travel = "出差" in leave_bits
            if loc is None and not has_leave_travel:
                continue

            overseas = bool(_address_hits_overseas(loc or "", overseas_keywords))
            symbol = "＄" if overseas else "￥"
            side_field: dict[str, bool] = {"in": False, "out": False}
            for p in day_punches:
                side = str(getattr(p, "side", "") or "")
                # SIDE_IN / SIDE_OUT constants are usually "in"/"out" or 上班/下班
                side_key = None
                if side in {"in", "上班", SIDE_IN}:  # type: ignore[name-defined]
                    side_key = "in"
                elif side in {"out", "下班", SIDE_OUT}:  # type: ignore[name-defined]
                    side_key = "out"
                if not side_key:
                    continue
                addr = str(getattr(p, "address", "") or "")
                status = str(getattr(p, "status", "") or "")
                if "缺卡" in status:
                    continue
                if _address_hits_overseas(addr, overseas_keywords):
                    overseas = True
                    symbol = "＄"
                kind = getattr(
                    _classify_side(address=addr, status=status, base_site=base),
                    "kind",
                    "",
                )
                la = str(getattr(p, "leave_apply", "") or "")
                # Never upgrade 驻地公司打卡 to ￥/＄ just because leave_apply/approval still
                # echo 出差 — that fights 回司裁剪 (何继成 8/6 等).
                if kind in {"field", "other_company"}:
                    side_field[side_key] = True
                elif kind != "base_company" and ("出差" in la or loc is not None):
                    side_field[side_key] = True

            cur_in = str(cell.get("in", "") or "")
            cur_out = str(cell.get("out", "") or "")
            missingish = {"", "×", "x", "X", "k", "K"}
            # Only upgrade present-like punched sides to travel; never fill missing side.
            if side_field["in"] and cur_in not in missingish and cur_in not in {"￥", "＄"}:
                cell["in"] = symbol
            if side_field["out"] and cur_out not in missingish and cur_out not in {"￥", "＄"}:
                cell["out"] = symbol
            syms[day_key] = cell
    return result


def compute_month(  # type: ignore[no-redef]
    *,
    year: int,
    month: int,
    roster: list,
    travel: list,
    leave: list,
    punch: list,
    work_dates: set,
    overseas_keywords: list,
    resolutions: dict | None = None,
    default_base_site: str | None = DEFAULT_BASE_SITE,
):
    roster_eff = apply_default_base_site(roster, default_base_site=default_base_site)
    base_default = default_base_site or ""
    punch_list = _sanitize_false_base_on_mixed_field_days(
        list(punch or []),
        roster_eff,
        overseas_keywords=list(overseas_keywords or []),
        default_base_site=base_default or DEFAULT_BASE_SITE,
    )
    travel_eff = shift_travel_start_past_predeparture_base(
        list(travel or []),
        punch_list,
        roster_eff,
        default_base_site=base_default or DEFAULT_BASE_SITE,
        overseas_keywords=list(overseas_keywords or []),
    )
    travel_eff = synthesize_overseas_travel_from_punches(
        travel_eff,
        punch_list,
        roster_eff,
        overseas_keywords=list(overseas_keywords or []),
        year=year,
        month=month,
        default_base_site=base_default or DEFAULT_BASE_SITE,
    )
    travel_eff = synthesize_domestic_field_travel_from_punches(
        travel_eff,
        punch_list,
        roster_eff,
        year=year,
        month=month,
        default_base_site=base_default or DEFAULT_BASE_SITE,
        overseas_keywords=list(overseas_keywords or []),
    )
    # Align punch↔roster names after normalize. Preserve「已离职」markers from punch
    # onto roster so departed cutoff still applies when花名册 omits the mark.
    departed_keys = {
        normalize_person_name(getattr(p, "person_name", ""))
        for p in punch_list
        if person_name_marked_departed(str(getattr(p, "person_name", "") or ""))
    }
    roster_named = []
    for person in roster_eff:
        key = normalize_person_name(getattr(person, "name", ""))
        raw = str(getattr(person, "name", "") or "")
        if key in departed_keys and not person_name_marked_departed(raw):
            roster_named.append(_dc_replace(person, name=f"{raw}（已离职）"))
        else:
            roster_named.append(person)
    roster_eff = roster_named
    roster_by_key = {
        normalize_person_name(getattr(p, "name", "")): getattr(p, "name", "")
        for p in roster_eff
    }
    punch_eff = []
    for p in punch_list:
        key = normalize_person_name(getattr(p, "person_name", ""))
        canon = roster_by_key.get(key)
        if canon and canon != getattr(p, "person_name", None):
            punch_eff.append(_dc_replace(p, person_name=canon))
        else:
            punch_eff.append(p)
    travel_named = []
    for row in travel_eff:
        key = normalize_person_name(getattr(row, "applicant", ""))
        canon = roster_by_key.get(key)
        if canon and canon != getattr(row, "applicant", None):
            travel_named.append(_dc_replace(row, applicant=canon))
        else:
            travel_named.append(row)
    leave_named = []
    for row in leave or []:
        key = normalize_person_name(getattr(row, "applicant", ""))
        canon = roster_by_key.get(key)
        if canon and canon != getattr(row, "applicant", None):
            leave_named.append(_dc_replace(row, applicant=canon))
        else:
            leave_named.append(row)
    result = _orig_compute_month(
        year=year,
        month=month,
        roster=roster_eff,
        travel=travel_named,
        leave=leave_named,
        punch=punch_eff,
        work_dates=work_dates,
        overseas_keywords=overseas_keywords,
        resolutions=resolutions,
    )
    return align_travel_symbol_on_punched_side_keep_missing(
        result,
        travel=travel_named,
        punch=punch_eff,
        roster=roster_eff,
        overseas_keywords=list(overseas_keywords or []),
        default_base_site=base_default or DEFAULT_BASE_SITE,
    )


